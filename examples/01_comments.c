// Тест 1: однострочные и блочные комментарии
/* Блочный комментарий
   на несколько строк.
   Вложенные звёзды * внутри — допустимы. */
#include <stdio.h>

/* Функция main с комментариями внутри тела */
int main() {
    int a = 1; // однострочный комментарий в конце строки
    /* блочный комментарий внутри тела */
    a = a + 2; /* комментарий после инструкции */
    // int скрытая = 0; — закомментированный код
    printf("%d\n", a); /* вывод: 3 */
    return 0; // конец main
}
